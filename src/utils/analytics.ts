/**
 * Epley 1RM formula: weight * (1 + reps / 30).
 * Returns exact weight when reps === 1.
 */
export function calculateEpley1RM(weight: number, reps: number): number {
  if (!Number.isFinite(weight) || !Number.isFinite(reps) || weight <= 0 || reps <= 0) {
    return 0;
  }
  if (reps === 1) return Number(weight.toFixed(1));
  return Number((weight * (1 + reps / 30)).toFixed(1));
}

/**
 * Returns the all-time best Epley Estimated 1RM for an exercise from completed workout history
 * (considering Normal and Failure sets).
 */
export function getHistoricalBest1RM(history: CompletedWorkout[], exerciseId: string): number {
  let best = 0;
  for (const session of history) {
    for (const ex of session.exercises) {
      if (ex.exerciseId !== exerciseId) continue;
      for (const s of ex.sets) {
        if (s.type === 'W') continue;
        const est = s.est1RM || calculateEpley1RM(s.weight, s.reps);
        if (est > best) best = est;
      }
    }
  }
  return best;
}

/**
 * Returns true if a workout session was generated by Demo Mode.
 * Supports legacy demo sessions saved prior to explicit isDemo tagging via `demo-` ID prefix.
 */
export function isDemoWorkout(workout: CompletedWorkout): boolean {
  if (typeof workout.isDemo === 'boolean') return workout.isDemo;
  return workout.id.startsWith('demo-');
}

/**
 * Chronologically recalculates est1RM, per-set isPR, and per-session prCount purely from the
 * provided workout sessions (sorted newest-first on return). Used after clearing Demo data
 * so real user PRs, 1RM, and XP are 100% accurate with zero demo contamination.
 */
export function recalculateHistoryPRs(sessions: CompletedWorkout[]): CompletedWorkout[] {
  const chronological = [...sessions].sort(
    (a, b) => new Date(a.date).getTime() - new Date(b.date).getTime()
  );

  const runningBestByExercise: Record<string, number> = {};

  const recalculated = chronological.map((session) => {
    const sessionIsDemo = isDemoWorkout(session);
    let prCount = 0;
    let totalVolume = 0;
    let totalWorkingSets = 0;

    const exercises = session.exercises.map((ex) => {
      let bestSoFar = runningBestByExercise[ex.exerciseId] ?? 0;

      const sets = ex.sets.map((s) => {
        const est1RM = calculateEpley1RM(s.weight, s.reps);
        const isPR = s.type !== 'W' && est1RM > 0 && est1RM > bestSoFar;
        totalVolume += s.weight * s.reps;
        if (s.type !== 'W') totalWorkingSets += 1;
        if (isPR) {
          bestSoFar = est1RM;
          prCount += 1;
        }
        return {
          ...s,
          est1RM,
          isPR,
          isDemo: sessionIsDemo,
        };
      });

      runningBestByExercise[ex.exerciseId] = bestSoFar;
      return {
        ...ex,
        sets,
      };
    });

    return {
      ...session,
      isDemo: sessionIsDemo,
      totalVolume: Math.round(totalVolume),
      totalWorkingSets,
      prCount,
      exercises,
    };
  });

  return recalculated.sort(
    (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime()
  );
}

/**
 * Returns the sets from the most recent completed session containing the given exercise.
 */
export function getPreviousExerciseSets(
  history: CompletedWorkout[],
  exerciseId: string
): CompletedSet[] {
  const sorted = [...history].sort(
    (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime()
  );
  for (const session of sorted) {
    const found = session.exercises.find((e) => e.exerciseId === exerciseId);
    if (found && found.sets.length > 0) {
      return found.sets;
    }
  }
  return [];
}

export interface ExerciseProgressPoint {
  dateLabel: string;
  isoDate: string;
  est1RM: number;
  maxWeight: number;
  bestSetLabel: string;
}

/**
 * Computes chronological Estimated 1RM & Max Weight progression points for an exercise.
 */
export function getExerciseProgression(
  history: CompletedWorkout[],
  exerciseId: string
): ExerciseProgressPoint[] {
  const chronological = [...history].sort(
    (a, b) => new Date(a.date).getTime() - new Date(b.date).getTime()
  );

  const points: ExerciseProgressPoint[] = [];

  for (const session of chronological) {
    const ex = session.exercises.find((e) => e.exerciseId === exerciseId);
    if (!ex || ex.sets.length === 0) continue;

    const workingSets = ex.sets.filter((s) => s.type !== 'W' && s.weight > 0 && s.reps > 0);
    const pool = workingSets.length > 0 ? workingSets : ex.sets.filter((s) => s.weight > 0 && s.reps > 0);
    if (pool.length === 0) continue;

    let best1RM = 0;
    let maxWeight = 0;
    let bestSet = pool[0];

    for (const s of pool) {
      const est = s.est1RM || calculateEpley1RM(s.weight, s.reps);
      if (est > best1RM) {
        best1RM = est;
        bestSet = s;
      }
      if (s.weight > maxWeight) {
        maxWeight = s.weight;
      }
    }

    points.push({
      dateLabel: formatShortThaiDate(session.date),
      isoDate: session.date,
      est1RM: Number(best1RM.toFixed(1)),
      maxWeight: Number(maxWeight.toFixed(1)),
      bestSetLabel: `${formatNumber(bestSet.weight)}kg × ${bestSet.reps}`,
    });
  }

  return points;
}

export interface WeeklyVolumePoint {
  weekKey: string;
  label: string;
  volume: number;
  sessions: number;
}

/**
 * Aggregates total volume (kg) by week (last 6 weeks that have data, or last 4 calendar weeks).
 */
export function getWeeklyVolumeData(history: CompletedWorkout[]): WeeklyVolumePoint[] {
  if (history.length === 0) return [];

  const getWeekStart = (d: Date) => {
    const date = new Date(d);
    const day = date.getDay();
    const diff = day === 0 ? -6 : 1 - day; // Monday start
    date.setDate(date.getDate() + diff);
    date.setHours(0, 0, 0, 0);
    return date;
  };

  const buckets = new Map<string, { start: Date; volume: number; sessions: number }>();

  for (const session of history) {
    const start = getWeekStart(new Date(session.date));
    const key = start.toISOString().slice(0, 10);
    const existing = buckets.get(key) ?? { start, volume: 0, sessions: 0 };
    existing.volume += session.totalVolume;
    existing.sessions += 1;
    buckets.set(key, existing);
  }

  return Array.from(buckets.entries())
    .sort((a, b) => a[1].start.getTime() - b[1].start.getTime())
    .slice(-6)
    .map(([weekKey, data]) => ({
      weekKey,
      label: `สัปดาห์ ${formatShortThaiDate(data.start.toISOString())}`,
      volume: Math.round(data.volume),
      sessions: data.sessions,
    }));
}

export interface MuscleSetBalanceItem {
  muscle: MuscleGroup;
  labelTh: string;
  labelEn: string;
  sets: number;
  status: 'low' | 'optimal' | 'high';
}

/**
 * Computes total working sets (Normal + Failure) in the last 7 days per muscle group.
 */
export function getWeeklyMuscleBalance(history: CompletedWorkout[]): MuscleSetBalanceItem[] {
  const cutoff = Date.now() - 7 * 24 * 60 * 60 * 1000;
  const counts: Record<MuscleGroup, number> = {
    Chest: 0,
    Back: 0,
    Shoulders: 0,
    Legs: 0,
    Biceps: 0,
    Triceps: 0,
    Abs: 0,
  };

  for (const session of history) {
    if (new Date(session.date).getTime() < cutoff) continue;
    for (const ex of session.exercises) {
      const def = EXERCISE_MAP[ex.exerciseId];
      if (!def) continue;
      const workingCount = ex.sets.filter((s) => s.type !== 'W').length;
      counts[def.muscle] += workingCount;
    }
  }

  return MUSCLE_GROUPS.map((m) => {
    const sets = counts[m.id];
    const status = sets < 10 ? 'low' : sets <= 20 ? 'optimal' : 'high';
    return {
      muscle: m.id,
      labelTh: m.labelTh,
      labelEn: m.labelEn,
      sets,
      status,
    };
  });
}

export type MuscleReadinessStatus = 'recovering' | 'ready' | 'low_volume';

export interface MuscleReadinessItem {
  muscle: MuscleGroup;
  labelTh: string;
  labelEn: string;
  weeklySets: number;
  hoursSinceLastTrained: number | null;
  recoveryPct: number;
  status: MuscleReadinessStatus;
  statusLabelTh: string;
  statusLabelEn: string;
  lastTrainedText: string;
}

/**
 * Calculates Muscle Recovery & Readiness HUD status for all 6 muscle groups:
 * - "recovering" (< 48h since last working set)
 * - "low_volume" (>= 48h or untrained while user has logs, and weekly sets < 10)
 * - "ready" (>= 48h rested and weekly sets >= 10, or fresh clean 0-state ready for Session #1)
 */
export function getMuscleReadinessHud(history: CompletedWorkout[]): MuscleReadinessItem[] {
  const nowMs = Date.now();
  const sevenDaysCutoff = nowMs - 7 * 24 * 60 * 60 * 1000;

  const weeklySets: Record<MuscleGroup, number> = {
    Chest: 0,
    Back: 0,
    Shoulders: 0,
    Legs: 0,
    Biceps: 0,
    Triceps: 0,
    Abs: 0,
  };

  const lastTrainedMs: Record<MuscleGroup, number | null> = {
    Chest: null,
    Back: null,
    Shoulders: null,
    Legs: null,
    Biceps: null,
    Triceps: null,
    Abs: null,
  };

  for (const session of history) {
    const ts = new Date(session.date).getTime();
    if (!Number.isFinite(ts)) continue;

    for (const ex of session.exercises) {
      const def = EXERCISE_MAP[ex.exerciseId];
      if (!def) continue;
      const workingCount = ex.sets.filter((s) => s.type !== 'W').length;
      if (workingCount <= 0) continue;

      if (ts >= sevenDaysCutoff) {
        weeklySets[def.muscle] += workingCount;
      }
      const prevTs = lastTrainedMs[def.muscle];
      if (prevTs === null || ts > prevTs) {
        lastTrainedMs[def.muscle] = ts;
      }
    }
  }

  const hasHistory = history.length > 0;

  return MUSCLE_GROUPS.map((m) => {
    const sets = weeklySets[m.id];
    const lastTs = lastTrainedMs[m.id];
    const hoursSince =
      lastTs !== null ? Math.max(0, (nowMs - lastTs) / (1000 * 60 * 60)) : null;

    let status: MuscleReadinessStatus;
    let statusLabelTh: string;
    let statusLabelEn: string;

    if (hoursSince !== null && hoursSince < 48) {
      status = 'recovering';
      statusLabelTh = 'กำลังฟื้นตัว';
      statusLabelEn = 'Recovering';
    } else if (hasHistory && sets < 10) {
      status = 'low_volume';
      statusLabelTh = 'ฝึกน้อยไป';
      statusLabelEn = 'Low Volume';
    } else {
      status = 'ready';
      statusLabelTh = 'พร้อมฝึก';
      statusLabelEn = 'Ready';
    }

    const recoveryPct =
      hoursSince === null ? 100 : Math.min(100, Math.round((hoursSince / 48) * 100));

    let lastTrainedText: string;
    if (hoursSince === null) {
      lastTrainedText = 'ยังไม่เคยฝึก';
    } else if (hoursSince < 1) {
      lastTrainedText = 'เพิ่งฝึกเมื่อครู่';
    } else if (hoursSince < 48) {
      lastTrainedText = `ฝึกเมื่อ ${Math.round(hoursSince)} ชม. ก่อน`;
    } else {
      const days = Math.floor(hoursSince / 24);
      lastTrainedText = `พักแล้ว ${days} วัน (${Math.round(hoursSince)} ชม.)`;
    }

    return {
      muscle: m.id,
      labelTh: m.labelTh,
      labelEn: m.labelEn,
      weeklySets: sets,
      hoursSinceLastTrained: hoursSince,
      recoveryPct,
      status,
      statusLabelTh,
      statusLabelEn,
      lastTrainedText,
    };
  });
}

export function formatShortThaiDate(iso: string): string {
  const d = new Date(iso);
  const months = [
    'ม.ค.',
    'ก.พ.',
    'มี.ค.',
    'เม.ย.',
    'พ.ค.',
    'มิ.ย.',
    'ก.ค.',
    'ส.ค.',
    'ก.ย.',
    'ต.ค.',
    'พ.ย.',
    'ธ.ค.',
  ];
  return `${d.getDate()} ${months[d.getMonth()]}`;
}

export function formatFullThaiDate(iso: string): string {
  const d = new Date(iso);
  return `${formatShortThaiDate(iso)} ${d.getFullYear() + 543}`;
}

export function formatDuration(seconds: number): string {
  const s = Math.max(0, Math.floor(seconds));
  const hrs = Math.floor(s / 3600);
  const mins = Math.floor((s % 3600) / 60);
  const secs = s % 60;
  if (hrs > 0) {
    return `${hrs}:${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`;
  }
  return `${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`;
}

export function formatNumber(n: number): string {
  if (!Number.isFinite(n)) return '0';
  return Number.isInteger(n) ? n.toLocaleString('en-US') : n.toFixed(1).replace(/\.0$/, '');
}

/**
 * Plays a futuristic "GO!" launch chord when the rest timer reaches 0.
 */
export function playTimerChime(enabled = true): void {
  if (!enabled) return;
  try {
    const AudioCtx =
      window.AudioContext ||
      (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
    if (!AudioCtx) return;
    const ctx = new AudioCtx();
    const now = ctx.currentTime;

    [880, 1174.66, 1318.51].forEach((freq, i) => {
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      osc.type = i === 2 ? 'triangle' : 'sine';
      const t0 = now + i * 0.055;
      osc.frequency.setValueAtTime(freq, t0);
      gain.gain.setValueAtTime(0.001, t0);
      gain.gain.exponentialRampToValueAtTime(0.095, t0 + 0.015);
      gain.gain.exponentialRampToValueAtTime(0.0001, t0 + 0.34);
      osc.connect(gain);
      gain.connect(ctx.destination);
      osc.start(t0);
      osc.stop(t0 + 0.36);
    });
  } catch {
    // Ignore autoplay or Web Audio restrictions gracefully
  }
}

/**
 * Plays a sharp futuristic 3-2-1 countdown beep in the final 3 seconds of rest.
 */
export function playRestCountdownBeep(secondsLeft: number, enabled = true): void {
  if (!enabled) return;
  if (secondsLeft < 1 || secondsLeft > 3) return;
  try {
    const AudioCtx =
      window.AudioContext ||
      (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
    if (!AudioCtx) return;
    const ctx = new AudioCtx();
    const now = ctx.currentTime;

    const freqMap: Record<number, number> = { 3: 660, 2: 740, 1: 880 };
    const freq = freqMap[secondsLeft] ?? 740;

    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.type = 'triangle';
    osc.frequency.setValueAtTime(freq, now);
    gain.gain.setValueAtTime(0.001, now);
    gain.gain.exponentialRampToValueAtTime(0.075, now + 0.008);
    gain.gain.exponentialRampToValueAtTime(0.0001, now + 0.13);
    osc.connect(gain);
    gain.connect(ctx.destination);
    osc.start(now);
    osc.stop(now + 0.14);
  } catch {
    // Ignore Web Audio restrictions gracefully
  }
}

